def emit_scalar_table(piece: dict):
    """A RE_UINT8 or RE_UINT16 table. Returns the C# lines, the element count and the index."""
    values = split_values(piece['body'])
    name = pascal(piece['name'])
    lines = []
    if piece['comment']:
        lines.append(f'    // {piece["comment"]}')
    if piece['type'] == 'RE_UINT8':
        # A ReadOnlySpan<byte> over a literal is emitted as RVA static data: no allocation,
        # no static constructor, and the JIT can fold the bounds check.
        lines.append(f'    internal static ReadOnlySpan<byte> {name} =>')
        lines.append('    [')
        lines.extend(_wrap(values, 16, '        '))
        lines.append('    ];')
    elif piece['type'] == 'RE_UINT16':
        # ReadOnlySpan RVA data is byte-only, so a 16-bit table is a static array. Roslyn
        # still emits it as a metadata blob plus RuntimeHelpers.InitializeArray, which
        # handles endianness, rather than as element-wise stores.
        lines.append(f'    internal static readonly ushort[] {name} = new ushort[]')
        lines.append('    {')
        lines.extend(_wrap(values, 12, '        '))
        lines.append('    };')
    else:
        raise Fail(f'{piece["name"]}: unexpected scalar table type {piece["type"]}')
    return lines, len(values), [(piece['name'], name)]


def _wrap(values: list[str], per_line: int, indent: str) -> list[str]:
    out = []
    for i in range(0, len(values), per_line):
        out.append(indent + ', '.join(values[i:i + per_line]) + ',')
    return out


def emit_strings(piece: dict) -> tuple[list[str], int]:
    values = re.findall(r'"((?:[^"\\]|\\.)*)"', piece['body'])
    for value in values:
        # C and C# escapes agree on the plausible set, but nothing in these names should
        # need escaping at all, so anything that does is a shape we have not seen.
        if '\\' in value:
            raise Fail(f're_strings: {value!r} contains an escape')
    lines = [
        '    /// <summary>Upstream <c>re_strings</c>: the property and value names.</summary>',
        '    internal static readonly string[] Strings = new string[]', '    {']
    for v in values:
        lines.append(f'        "{v}",')
    lines.append('    };')
    return lines, len(values), []


def emit_struct_table(piece: dict, fields: list[tuple[str, str, int]]) -> tuple[list[str], int]:
    """A struct array, emitted as one flat array per field.

    Naming each field's array after the field makes an accidental field-order swap - the
    classic transliteration bug in a struct table - impossible to write.
    """
    rows = _parse_struct_rows(piece['body'])
    lines: list[str] = []
    index: list[tuple[str, str]] = []
    if piece['comment']:
        lines.append(f'    // {piece["comment"]}')
    for column, (c_field, cs_field, cs_type, arity) in enumerate(fields):
        flat: list[str] = []
        for row in rows:
            cell = row[column]
            if len(cell) > arity:
                raise Fail(f'{piece["name"]}: {c_field} has {len(cell)} values, max {arity}')
            # C zero-fills a partly initialised aggregate.
            flat.extend(cell + ['0'] * (arity - len(cell)))
        member = pascal(piece['name']) + cs_field
        suffix = f' (stride {arity})' if arity > 1 else ''
        lines.append(f'    // {piece["name"]}[].{c_field}{suffix}')
        lines.append(f'    internal static readonly {cs_type}[] {member} = new {cs_type}[]')
        lines.append('    {')
        lines.extend(_wrap(flat, 12, '        '))
        lines.append('    };')
        index.append((f'{piece["name"]}.{c_field}', member))
    return lines, len(rows), index


def _parse_struct_rows(body: str) -> list[list[list[str]]]:
    """``{ 1, { 454, 0}},`` -> ``[['1'], ['454', '0']]`` per row."""
    rows = []
    for raw in body.split('\n'):
        # `{ 195,  0,  0}, /* ALPHABETIC */` - the trailing comment names the entry, which
        # re_strings already carries, so it is dropped.
        line = re.sub(r'/\*.*?\*/', '', raw).strip().rstrip(',')
        if not line:
            continue
        if not (line.startswith('{') and line.endswith('}')):
            raise Fail(f'unexpected struct row {raw!r}')
        inner = line[1:-1]
        cells: list[list[str]] = []
        depth = 0
        current = ''
        for ch in inner:
            if ch == '{':
                depth += 1
                if depth == 1:
                    current = ''
                    continue
            if ch == '}':
                depth -= 1
                if depth == 0:
                    cells.append(split_values(current))
                    current = ''
                    continue
            if ch == ',' and depth == 0:
                if current.strip():
                    cells.append(split_values(current))
                current = ''
                continue
            current += ch
        if current.strip():
            cells.append(split_values(current))
        rows.append(cells)
    return rows


# --------------------------------------------------------------------------------------
# The generator
# --------------------------------------------------------------------------------------

# Which output file each top-level name goes to.
def area_of(name: str) -> str:
    if name in ('re_strings', 're_properties', 're_property_values'):
        return 'PropertyNames'
    if 'all_cases' in name or 'simple_folding' in name or 'full_folding' in name \
            or 'expand_on_folding' in name or 'case_folding' in name:
        return 'Casing'
    if name.startswith('script_extensions'):
        return 'ScriptExtensions'
    return 'Properties'


# The struct arrays, whose fields we split into one flat array each:
# (field name in the C struct, C# member suffix, C# element type, slots the C declaration gives).
PROPERTY_FIELDS = [('name', 'Name', 'ushort', 1), ('id', 'Id', 'byte', 1),
                   ('value_set', 'ValueSet', 'byte', 1)]
PROPERTY_VALUE_FIELDS = [('name', 'Name', 'ushort', 1), ('value_set', 'ValueSet', 'byte', 1),
                         ('id', 'Id', 'ushort', 1)]
ALL_CASES_FIELDS = [('delta', 'Delta', 'uint', 1), ('others', 'Others', 'ushort', 3)]
FULL_FOLDING_FIELDS = [('data', 'Data', 'ushort', 3)]


def build() -> tuple[dict[str, str], dict]:
    defines, externs = parse_header(H_PATH)
    pieces = parse_source(C_PATH)

    # --- constants -------------------------------------------------------------------
    const_lines: list[str] = []
    known: dict[str, str] = {}
    for c_name, value in defines + [(p['name'], p['value']) for p in pieces if p['kind'] == 'define']:
        cs = const_name(c_name)
        known[c_name] = cs
        if value.startswith('"'):
            const_lines.append(f'    /// <summary>Upstream <c>{c_name}</c>.</summary>')
            const_lines.append(f'    internal const string {cs} = {value};')
            continue
        expr = re.sub(r'\bRE_\w+\b', lambda m: known.get(m.group(0), m.group(0)), value)
        if 'RE_' in expr or re.fullmatch(r'[\w\s()|<>&+^*/-]+', expr) is None:
            raise Fail(f'{c_name}: unexpected constant expression {value!r} -> {expr!r}')
        # Every numeric constant is `int`. They all fit (the widest is RE_PROP_C_MASK,
        # 0x30020003), and `int` keeps `1 << PropZl` legal: C# demands an `int` shift count.
        const_lines.append(f'    /// <summary>Upstream <c>{c_name}</c>.</summary>')
        const_lines.append(f'    internal const int {cs} = {expr};')

    # --- everything else -------------------------------------------------------------
    areas: dict[str, list[str]] = {'Properties': [], 'Casing': [], 'ScriptExtensions': [],
                                   'PropertyNames': []}
    stats = {'tables': {}, 'functions': [], 'handPorted': [], 'typedefs': []}
    # (fixture key, C# member) for every numeric table, in file order. The fixture key is the C
    # name, suffixed with the struct field where one table became several.
    index: list[tuple[str, str]] = []
    property_functions: list[str] | None = None

    for piece in pieces:
        kind = piece['kind']
        if kind == 'define':
            continue
        if kind == 'typedef':
            stats['typedefs'].append(piece['name'])
            continue

        if kind == 'table':
            name = piece['name']
            area = area_of(name)
            if name == 're_strings':
                lines, count, entries = emit_strings(piece)
            elif name == 're_properties':
                lines, count, entries = emit_struct_table(piece, PROPERTY_FIELDS)
            elif name == 're_property_values':
                lines, count, entries = emit_struct_table(piece, PROPERTY_VALUE_FIELDS)
            elif piece['type'] == 'RE_AllCases':
                lines, count, entries = emit_struct_table(piece, ALL_CASES_FIELDS)
            elif piece['type'] == 'RE_FullCaseFolding':
                lines, count, entries = emit_struct_table(piece, FULL_FOLDING_FIELDS)
            elif piece['type'] == 'RE_GetPropertyFunc':
                property_functions = split_values(piece['body'])
                stats['tables'][name] = len(property_functions)
                continue
            else:
                lines, count, entries = emit_scalar_table(piece)
            index.extend(entries)
            stats['tables'][name] = count
            areas[area].extend(lines)
            areas[area].append('')
            continue

        if kind == 'function':
            name = piece['name']
            short = name[3:] if name.startswith('re_') else name
            if short in HAND_PORTED:
                digest = body_digest(piece['body'])
                if digest != HAND_PORTED[short]:
                    raise Fail(
                        f'{name}: upstream changed this function. UnicodeCasing.cs hand-ports it, '
                        f'so read the upstream diff, update the C# and re-pin the digest here:\n'
                        f"    '{short}': '{digest}',")
                stats['handPorted'].append(name)
                areas[area_of(name.replace('re_get_', ''))].append(
                    f'    // {name} is hand-ported in UnicodeCasing.cs: its body does not fit the '
                    'three-level-walk shape.')
                areas[area_of(name.replace('re_get_', ''))].append('')
                continue
            areas['Properties'].extend(translate_function(piece))
            areas['Properties'].append('')
            stats['functions'].append(name)
            continue

        raise Fail(f'unhandled piece {kind}')

    if property_functions is None:
        raise Fail('re_get_property table not found')

    # --- the property dispatch switch ------------------------------------------------
    dispatch = [
        "    /// <summary>The number of entries in upstream's <c>re_get_property</c> table.</summary>",
        f'    internal const int PropertyFunctionCount = {len(property_functions)};',
        '',
        '    /// <summary>Upstream <c>re_get_property[prop](codepoint)</c>.</summary>',
        '    internal static uint GetProperty(uint prop, uint codepoint) => prop switch',
        '    {',
    ]
    null_slots = []
    for slot, fn in enumerate(property_functions):
        if fn == '0':
            # Upstream leaves RE_PROP_SCX's slot NULL: script extensions are many-valued, so
            # unicode_has_property branches to re_get_script_extensions before it ever indexes
            # this table. Calling through the NULL is undefined behaviour in C; here it throws.
            null_slots.append(slot)
            dispatch.append(f'        {slot} => throw new InvalidOperationException('
                            f'"property {slot} is many-valued: use GetScriptExtensions"),')
            continue
        short = fn[3:] if fn.startswith('re_') else fn
        if short in HAND_PORTED:
            raise Fail(f'{fn} is in the dispatch table but hand-ported')
        dispatch.append(f'        {slot} => {pascal(fn)}(codepoint),')
    # Upstream's callers range-check `prop` before indexing, so nothing should reach here.
    dispatch.append('        _ => throw new ArgumentOutOfRangeException(nameof(prop)),')
    dispatch.append('    };')
    if null_slots != [86]:
        raise Fail(f'unexpected NULL slots in re_get_property: {null_slots}')
    areas['Properties'].extend([''] + dispatch)

    # --- the table index, for the fixture test ---------------------------------------
    accessor = [
        '    /// <summary>',
        '    /// Every numeric table, keyed by its name in the C source, so a test can walk them',
        '    /// all and check each one against a digest taken independently from that source.',
        '    /// A table that was one struct array in C appears once per field.',
        '    /// </summary>',
        '    /// <returns>The tables, in the order the C file declares them.</returns>',
        '    internal static List<(string Name, uint[] Values)> AllTables()',
        '    {',
        f'        List<(string Name, uint[] Values)> tables = new({len(index)});',
    ]
    for key, member in index:
        accessor.append(f'        tables.Add(("{key}", ToValues({member})));')
    accessor.extend([
        '        return tables;',
        '    }',
        '',
        '    private static uint[] ToValues(ReadOnlySpan<byte> table)',
        '    {',
        '        uint[] values = new uint[table.Length];',
        '        for (int i = 0; i < table.Length; i++)',
        '        {',
        '            values[i] = table[i];',
        '        }',
        '',
        '        return values;',
        '    }',
        '',
        '    private static uint[] ToValues(ushort[] table)',
        '    {',
        '        uint[] values = new uint[table.Length];',
        '        for (int i = 0; i < table.Length; i++)',
        '        {',
        '            values[i] = table[i];',
        '        }',
        '',
        '        return values;',
        '    }',
        '',
        '    private static uint[] ToValues(byte[] table)',
        '    {',
        '        uint[] values = new uint[table.Length];',
        '        for (int i = 0; i < table.Length; i++)',
        '        {',
        '            values[i] = table[i];',
        '        }',
        '',
        '        return values;',
        '    }',
        '',
        '    private static uint[] ToValues(uint[] table) => (uint[])table.Clone();',
    ])

    files = {}
    for area, lines in areas.items():
        text = HEADER.format(ext='c', ns=NAMESPACE, cls=CLASS)
        body = '\n'.join(lines).rstrip('\n')
        files[f'Unicode{area}.g.cs'] = text + body + '\n' + FOOTER

    const_text = HEADER.format(ext='h', ns=NAMESPACE, cls=CLASS)
    files['UnicodeConstants.g.cs'] = const_text + '\n'.join(const_lines) + '\n' + FOOTER
    files['UnicodeTableIndex.g.cs'] = (HEADER.format(ext='c', ns=NAMESPACE, cls=CLASS)
                                       + '\n'.join(accessor) + '\n' + FOOTER)

    stats['externs'] = externs
    stats['index'] = index
    stats['propertyFunctionCount'] = len(property_functions)
    return files, stats


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true',
                        help='fail if the committed files differ from what would be written')
    args = parser.parse_args()

    files, stats = build()

    # Consumption assertions: everything the header declares must have been emitted, at the
    # length the header declares. A silently dropped or truncated table is the failure this
    # whole script exists to make impossible.
    for extern, length in stats['externs'].items():
        if extern not in stats['tables']:
            raise Fail(f'{extern} is declared in the header but was not emitted')
        if stats['tables'][extern] != length:
            raise Fail(f'{extern}: header declares {length} entries, emitted '
                       f'{stats["tables"][extern]}')
    total_functions = len(stats['functions']) + len(stats['handPorted'])
    if total_functions != 104:
        raise Fail(f'expected 104 lookup functions, consumed {total_functions}')
    if sorted(n[3:] for n in stats['handPorted']) != sorted(HAND_PORTED):
        raise Fail(f'hand-ported set changed: {stats["handPorted"]}')
    if len(stats['tables']) != 253:
        raise Fail(f'expected 253 tables, consumed {len(stats["tables"])}')

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    changed = []
    for name, text in files.items():
        path = OUT_DIR / name
        existing = path.read_text(encoding='utf-8') if path.exists() else None
        if existing != text:
            changed.append(name)
            if not args.check:
                path.write_text(text, encoding='utf-8', newline='\n')

    if args.check:
        if changed:
            print('transliterate-unicode: OUT OF DATE - ' + ', '.join(changed), file=sys.stderr)
            return 1
        print('transliterate-unicode: up to date')
        return 0

    total_elements = sum(stats['tables'].values())
    print(f'tables:    {len(stats["tables"])} ({total_elements} elements)')
    print(f'functions: {len(stats["functions"])} transliterated, '
          f'{len(stats["handPorted"])} hand-ported')
    print(f'files:     {", ".join(sorted(files))}')
    if changed:
        print('changed:   ' + ', '.join(sorted(changed)))
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except Fail as exc:
        print(f'transliterate-unicode: {exc}', file=sys.stderr)
        sys.exit(2)
