def body_digest(body: str) -> str:
    return hashlib.sha256(' '.join(body.split()).encode('utf-8')).hexdigest()


# --------------------------------------------------------------------------------------
# Names
# --------------------------------------------------------------------------------------

def pascal(c_name: str) -> str:
    """``re_alphabetic_table_1`` -> ``AlphabeticTable1``; ``re_get_word`` -> ``GetWord``."""
    name = c_name[3:] if c_name.startswith('re_') else c_name
    return ''.join(part.capitalize() for part in name.split('_') if part)


def const_name(c_name: str) -> str:
    """``RE_PROP_GC`` -> ``PropGc``, ``RE_MAX_CASES`` -> ``MaxCases``."""
    name = c_name[3:] if c_name.startswith('RE_') else c_name
    return ''.join(part.capitalize() for part in name.split('_') if part)


# --------------------------------------------------------------------------------------
# Parsing the C source
# --------------------------------------------------------------------------------------

class Fail(Exception):
    pass


class Source:
    def __init__(self, text: str, path: Path):
        self.text = text
        self.path = path
        self.pos = 0

    def line_of(self, pos: int) -> int:
        return self.text.count('\n', 0, pos) + 1

    def fail(self, message: str) -> None:
        raise Fail(f'{self.path.name}:{self.line_of(self.pos)}: {message}\n'
                   f'  next: {self.text[self.pos:self.pos + 120]!r}')

    def skip_trivia(self) -> str | None:
        """Skip blank lines and block comments. Returns the last comment's text."""
        comment = None
        while self.pos < len(self.text):
            m = re.compile(r'[ \t\r\n]+').match(self.text, self.pos)
            if m:
                self.pos = m.end()
                continue
            m = re.compile(r'/\*(.*?)\*/', re.S).match(self.text, self.pos)
            if m:
                comment = ' '.join(m.group(1).split())
                self.pos = m.end()
                continue
            break
        return comment

    def try_match(self, pattern: str, flags: int = 0) -> re.Match | None:
        m = re.compile(pattern, flags).match(self.text, self.pos)
        if m:
            self.pos = m.end()
        return m


def parse_header(path: Path) -> tuple[list[tuple[str, str]], dict[str, int]]:
    """Returns the ``#define``s as (name, value) and the extern arrays as name -> length."""
    src = Source(path.read_text(encoding='utf-8'), path)
    defines: list[tuple[str, str]] = []
    externs: dict[str, int] = {}
    ignorable = (
        r'typedef\s+[^;{]+;',                       # scalar typedefs
        r'typedef\s+struct\s+\w+\s*\{[^}]*\}\s*\w+;',  # struct typedefs
        r'typedef\s+\w+\s*\(\*\w+\)\([^)]*\);',     # function-pointer typedef
        r'#if[^\n]*\n(?:[^\n]*\n)*?#endif\n',       # the FALSE/TRUE guard
        r'(?:RE_UINT32|int)\s+re_\w+\([^)]*\);',    # function declarations
    )
    while True:
        src.skip_trivia()
        if src.pos >= len(src.text):
            break
        m = src.try_match(r'#define\s+(\w+)\s+([^\n]*)\n')
        if m:
            defines.append((m.group(1), m.group(2).strip()))
            continue
        m = src.try_match(r'extern\s+[\w*]+\s+(\w+)\[(\d+)\];')
        if m:
            externs[m.group(1)] = int(m.group(2))
            continue
        if any(src.try_match(p) for p in ignorable):
            continue
        src.fail('unrecognised construct in the header')
    return defines, externs


def split_values(body: str) -> list[str]:
    return [v.strip() for v in body.split(',') if v.strip()]


def parse_source(path: Path):
    """Walks the C file, consuming every construct. Returns the pieces in file order."""
    src = Source(path.read_text(encoding='utf-8'), path)
    pieces: list[dict] = []

    src.skip_trivia()
    if not src.try_match(r'#include\s+"_regex_unicode\.h"\n'):
        src.fail('expected the header include first')

    while True:
        comment = src.skip_trivia()
        if src.pos >= len(src.text):
            break

        m = src.try_match(r'#define\s+(\w+)\s+([^\n]*)\n')
        if m:
            pieces.append({'kind': 'define', 'name': m.group(1), 'value': m.group(2).strip()})
            continue

        m = src.try_match(r'typedef\s+struct\s*\{(.*?)\}\s*(\w+);', re.S)
        if m:
            pieces.append({'kind': 'typedef', 'name': m.group(2), 'body': m.group(1)})
            continue

        # A table: [static] TYPE name[] = { ... \n};
        m = src.try_match(r'(?:(static)\s+)?([\w*]+)\s+(\w+)\[\]\s*=\s*\{(.*?)\n\};\n', re.S)
        if m:
            pieces.append({
                'kind': 'table',
                'static': bool(m.group(1)),
                'type': m.group(2),
                'name': m.group(3),
                'body': m.group(4),
                'comment': comment,
            })
            continue

        # A function: RETTYPE name(args) { ... \n}
        m = src.try_match(r'(RE_UINT32|int)\s+(\w+)\(([^)]*)\)\s*\{(.*?)\n\}\n', re.S)
        if m:
            pieces.append({
                'kind': 'function',
                'ret': m.group(1),
                'name': m.group(2),
                'args': m.group(3),
                'body': m.group(4),
                'comment': comment,
            })
            continue

        src.fail('unrecognised top-level construct')

    return pieces


