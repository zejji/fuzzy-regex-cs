# Translating a lookup function
# --------------------------------------------------------------------------------------

# Every statement shape the 100 generic functions are built from. Each entry is
# (compiled pattern, formatter). A body line that matches none of them is a hard error.
def _statement_rules():
    def table(name: str) -> str:
        return pascal(name)

    return [
        (re.compile(r'RE_UINT32 (field_2|field_1|field_0|offset|v);'),
         lambda m: f'uint {m.group(1)};'),
        (re.compile(r'(field_2|field_1|field_0|offset|v) = codepoint >> (\d+);'),
         lambda m: f'{m.group(1)} = codepoint >> {m.group(2)};'),
        (re.compile(r'(field_2|field_1|field_0|offset|v) = \(codepoint >> (\d+)\) & (0x[0-9A-Fa-f]+);'),
         lambda m: f'{m.group(1)} = (codepoint >> {m.group(2)}) & {m.group(3)};'),
        (re.compile(r'(field_2|field_1|field_0|offset|v) = codepoint & (0x[0-9A-Fa-f]+);'),
         lambda m: f'{m.group(1)} = codepoint & {m.group(2)};'),
        # ReadOnlySpan<T>'s indexer takes an int, where a C array takes any integral type,
        # so an index computed in uint needs an explicit cast. Every index here is far below
        # int.MaxValue: the widest is codepoint >> 10, at most 0x43F.
        (re.compile(r'v = (\w+)\[(field_2|field_1|field_0)\];'),
         lambda m: f'v = {table(m.group(1))}[(int){m.group(2)}];'),
        (re.compile(r'v = (\w+)\[\(v << (\d+)\) \| (field_1|field_0)\];'),
         lambda m: f'v = {table(m.group(1))}[(int)((v << {m.group(2)}) | {m.group(3)})];'),
        # C# demands an int shift count where C takes any integral type.
        (re.compile(r'return \(v >> offset\) & (0x[0-9A-Fa-f]+);'),
         lambda m: f'return (v >> (int)offset) & {m.group(1)};'),
        (re.compile(r'return v;'), lambda m: 'return v;'),
        (re.compile(r'return (\d+);'), lambda m: f'return {m.group(1)};'),
        (re.compile(r'if \((0x[0-9A-Fa-f]+) <= codepoint && codepoint <= (0x[0-9A-Fa-f]+)\)'),
         lambda m: f'if ({m.group(1)} <= codepoint && codepoint <= {m.group(2)})'),
        (re.compile(r'if \(codepoint == (0x[0-9A-Fa-f]+)\)'),
         lambda m: f'if (codepoint == {m.group(1)})'),
    ]


STATEMENT_RULES = _statement_rules()


def _translate_statement(name: str, line: str) -> str:
    for pattern, fmt in STATEMENT_RULES:
        m = pattern.fullmatch(line)
        if m:
            return fmt(m)
    raise Fail(f'{name}: unrecognised statement {line!r}')


def translate_function(piece: dict) -> list[str]:
    """Translates one generic lookup function into C#."""
    name = piece['name']
    if piece['args'].strip() != 'RE_UINT32 codepoint':
        raise Fail(f'{name}: unexpected signature {piece["args"]!r}')
    if piece['ret'] != 'RE_UINT32':
        raise Fail(f'{name}: unexpected return type {piece["ret"]}')

    out = [f'    /// <summary>Upstream <c>{name}</c>.</summary>',
           f'    internal static uint {pascal(name)}(uint codepoint)', '    {']
    indent = '        '
    raw_lines = [raw.strip() for raw in piece['body'].split('\n')]
    i = 0
    while i < len(raw_lines):
        line = raw_lines[i]
        i += 1
        if not line:
            if out and out[-1] not in ('', '    {'):
                out.append('')
            continue
        translated = _translate_statement(name, line)
        if line.startswith('if ('):
            # C allows a bare statement after `if (...)`; the codebase always braces.
            while i < len(raw_lines) and not raw_lines[i]:
                i += 1
            if i >= len(raw_lines):
                raise Fail(f'{name}: `if` with no consequent')
            consequent = _translate_statement(name, raw_lines[i])
            i += 1
            out.append(indent + translated)
            out.append(indent + '{')
            out.append(indent + '    ' + consequent)
            out.append(indent + '}')
            continue
        out.append(indent + translated)
    while out and out[-1] == '':
        out.pop()
    out.append('    }')
    return out


