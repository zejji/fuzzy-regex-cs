#!/usr/bin/env python3
"""Transliterate upstream's generated Unicode tables into C#.

Reads ``upstream/src/_regex_unicode.c`` and ``upstream/src/_regex_unicode.h`` - both of which
upstream generates from the UCD with ``tools/build_regex_unicode.py`` - and writes
``src/FuzzyRegex/Unicode/*.g.cs``.

We transliterate upstream's *output* rather than porting its generator, so the tables are
identical to upstream's by construction and no UCD download is needed. See
``docs/plan/2026-08-30-phase2-decisions.md`` decision A.

The script consumes the C source exhaustively: it walks a cursor over the file and every
byte must be matched by a known construct (a comment, a ``#define``, a typedef, a table or a
function). A shape it has never seen is a hard error, so a future upstream file cannot
silently drop a table.

Four functions are *not* transliterated - ``re_get_all_cases``, ``re_get_simple_case_folding``,
``re_get_full_case_folding`` and ``re_get_script_extensions``. They index struct arrays and
their C bodies do not fit the three-level-walk shape the other 100 share; they are hand-ported
in ``src/FuzzyRegex/Unicode/UnicodeCasing.cs``. Their C bodies are pinned here by exact text,
so an upstream change to any of them fails this script rather than passing silently.

Usage:
    python tools/transliterate-unicode.py            # write the files
    python tools/transliterate-unicode.py --check    # fail if the committed files differ
"""

